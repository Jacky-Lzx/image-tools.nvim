vim.opt.rtp:prepend(vim.fn.getcwd())
local bootstrap = require("image_tools.bootstrap")
bootstrap.setup({ auto_preview = true, max_width = 47, transport = "direct" })
assert(not package.loaded.image_tools and not package.loaded["image_tools.runtime"])
assert(vim.fn.exists(":ImagePreview") == 2 and vim.fn.exists(":ImageInsert") == 2)
vim.bo.filetype = "markdown"
vim.api.nvim_buf_set_lines(0, 0, -1, false, { "plain prose" })
vim.wait(20, function()
  return false
end)
assert(not package.loaded.image_tools, "Plain text initialized the image backend")
assert(bootstrap.set_auto_preview(false) == false)
assert(bootstrap.set_auto_preview(false) == false)
assert(bootstrap.set_auto_preview(true) == true)
assert(bootstrap.toggle() == false and bootstrap.toggle() == true)
assert(not package.loaded.image_tools, "Toggle initialized the image backend")
local facade = require("image_tools")
assert(facade.status().configured == false and not package.loaded["image_tools.runtime"])
vim.cmd("ImagePreviewClose")
assert(facade.status().configured)
assert(facade._runtime().options.max_width == 47, "First command lost pending options")
assert(facade.status().transport == "direct")
facade.toggle()
assert(bootstrap.enabled() == false, "Read-only toggle state lost false")
assert(vim.fn.exists("#ImageToolsBootstrap") == 0, "Bootstrap handlers survived runtime setup")
print("Image-owned bootstrap: cold setup, native commands, pending configuration and toggle state passed")
