vim.opt.rtp:prepend(vim.fn.getcwd())
local plugin = require("image_tools")
local options =
  { auto_preview = false, transport = "direct", inline = { enabled = false }, buffer = { enabled = false } }
local caller = vim.deepcopy(options)
plugin.setup(options)
assert(vim.deep_equal(caller, options), "setup mutated caller configuration")
local commands = vim.api.nvim_get_commands({})
local handlers = vim.api.nvim_get_autocmds({})
assert(not pcall(plugin.setup, false), "setup(false) must reject an invalid configuration type")
assert(vim.deep_equal(commands, vim.api.nvim_get_commands({})), "Invalid setup replaced commands")
assert(vim.deep_equal(handlers, vim.api.nvim_get_autocmds({})), "Invalid setup replaced handlers")
plugin.setup(caller)
assert(#vim.api.nvim_get_autocmds({}) == #handlers, "Repeated setup duplicated automatic handlers")
print("image-tools.nvim: setup input isolation, invalid configuration and registration lifetime passed")

local runtime = plugin._runtime()
assert(not pcall(plugin.setup, { max_width = -1 }))
assert(plugin._runtime() == runtime and not runtime.disposed)
plugin.dispose()
plugin.dispose()
assert(runtime.disposed and not plugin.status().configured)
assert(vim.fn.exists("#image_tools") == 0)
local bootstrap = require("image_tools.bootstrap")
bootstrap.setup({ auto_preview = true, math = { enabled = false }, buffer = { enabled = false } })
local handlers = vim.api.nvim_get_autocmds({ group = "ImageToolsBootstrap" })
assert(not pcall(bootstrap.setup, { max_width = -1 }))
assert(vim.deep_equal(handlers, vim.api.nvim_get_autocmds({ group = "ImageToolsBootstrap" })))
vim.bo.filetype = "markdown"
vim.api.nvim_buf_set_lines(0, 0, -1, false, { "![](missing-image.png)" })
plugin.dispose()
vim.wait(30, function()
  return false
end)
assert(not plugin.status().configured, "Stale bootstrap work recreated a disposed runtime")
assert(vim.fn.exists("#ImageToolsBootstrap") == 0)
assert(vim.fn.exists(":ImagePreview") == 0)
plugin.setup(caller)
plugin.dispose()
